EMAIL_RE = re.compile(r"^[^@\s<>,;\"']+@[^@\s<>,;\"']+\.[^@\s<>,;\"']+$")
COLOURS = {"RED": "#b03a2e", "AMBER": "#b9770e", "GREEN": "#1e8449"}
ORDER = {"RED": 0, "AMBER": 1, "GREEN": 2}
AUDIENCES = {"exec", "team"}
TITLE_RE = re.compile(r"^# (.*) - weekly status \((\d{4}-\d{2}-\d{2})\)\s*$")
APPROVED_RE = re.compile(r"^STATUS: APPROVED by (.+) at (\S+)\s*$")


# ----------------------------------------------------------------------------------- parsing
@dataclass
class Row:
    workstream: str
    rag: str
    fallback: bool
    done: str
    overdue: str
    blocked: str
    stale: str
    why: str


@dataclass
class Report:
    program: str
    as_of: str
    approved_by: str | None
    approved_at: str | None
    generated_by: str
    rows: list[Row] = field(default_factory=list)
    decisions: list[str] = field(default_factory=list)
    overall: str | None = None   # set when this Report is a one-workstream slice of a bigger report

    def counts(self) -> dict[str, int]:
        c = {"RED": 0, "AMBER": 0, "GREEN": 0}
        for r in self.rows:
            c[r.rag] += 1
        return c

    def headline(self) -> str:
        if self.overall:
            return self.overall
        c = self.counts()
        return f"{c['RED']} RED, {c['AMBER']} AMBER, {c['GREEN']} GREEN"


def parse_report(text: str) -> Report:
    """Read the markdown report the agent wrote. Raises ValueError if it is not in that format."""
    lines = text.splitlines()
    m = next((TITLE_RE.match(ln) for ln in lines if ln.startswith("# ")), None)
    if not m:
        raise ValueError("not a status report: title line '# <program> - weekly status (YYYY-MM-DD)' not found")
    program, as_of = m.group(1), m.group(2)
    by = at = None
    generated = ""
    for ln in lines:
        am = APPROVED_RE.match(ln)
        if am:
            by, at = am.group(1), am.group(2)
        if ln.startswith("Generated by:"):
            generated = ln[len("Generated by:"):].split(". Counts and dates", 1)[0].strip().rstrip(".")
    rep = Report(program, as_of, by, at, generated)
    in_decisions = False
    for ln in lines:
        if ln.startswith("## Decisions needed"):
            in_decisions = True
            continue
        if in_decisions and ln.startswith("- "):
            rep.decisions.append(ln[2:].strip())
            continue
        if ln.startswith("| ") and not ln.startswith("| Workstream") and not ln.startswith("|---"):
            cells = [c.strip() for c in ln.strip().strip("|").split("|")]
            if len(cells) < 7:
                raise ValueError(f"table row has {len(cells)} columns, expected 7: {ln[:60]}")
            rag = cells[1].split()[0]
            if rag not in COLOURS:
                raise ValueError(f"unknown RAG {rag!r} in row for {cells[0]}")
            rep.rows.append(Row(cells[0], rag, "(fallback)" in cells[1], cells[2], cells[3], cells[4],
                                cells[5], "|".join(cells[6:])))
    if not rep.rows:
        raise ValueError("no workstream rows found in the report")
    rep.rows.sort(key=lambda r: (ORDER[r.rag], r.workstream))
    rep.decisions = [d for d in rep.decisions if not d.lower().startswith("none")]
    return rep


# ----------------------------------------------------------------------------------- config
def _check_addr(who: str, name: str, email: str, problems: list[str]) -> None:
    if not isinstance(name, str) or not name.strip() or any(ch in name for ch in "\r\n"):
        problems.append(f"{who}: invalid name")
    if not isinstance(email, str) or not EMAIL_RE.match(email):
        problems.append(f"{who}: invalid email {email!r}")


def load_config(path: str | Path) -> dict:
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"{p} not found. Copy config/stakeholders.example.json to {p} and edit it.")
    cfg = json.loads(p.read_text(encoding="utf-8"))
    problems: list[str] = []
    ap = cfg.get("approver") or {}
    _check_addr("approver", ap.get("name"), ap.get("email"), problems)
    esc = cfg.get("escalation")
    if esc is not None:
        _check_addr("escalation", esc.get("name"), esc.get("email"), problems)
    for key in ("after_hours", "escalate_after_hours"):
        v = (cfg.get("reminders") or {}).get(key)
        if v is not None and (not isinstance(v, (int, float)) or v <= 0):
            problems.append(f"reminders.{key} must be a positive number of hours")
    for i, s in enumerate(cfg.get("stakeholders", [])):
        _check_addr(f"stakeholders[{i}]", s.get("name"), s.get("email"), problems)
        if s.get("audience") not in AUDIENCES:
            problems.append(f"stakeholders[{i}]: audience must be one of {sorted(AUDIENCES)}")
    for ws, o in (cfg.get("workstream_owners") or {}).items():
        _check_addr(f"workstream_owners[{ws}]", o.get("name"), o.get("email"), problems)
        if o.get("slack_id") is not None and not re.match(r"^[UW][A-Z0-9]{6,}$", str(o["slack_id"])):
            problems.append(f"workstream_owners[{ws}]: slack_id must look like U01ABCDEF2 (Slack profile -> Copy member ID)")
    if problems:
        raise ValueError("invalid stakeholder config:\n  - " + "\n  - ".join(problems))
    cfg.setdefault("stakeholders", [])
    cfg.setdefault("workstream_owners", {})
    return cfg


# ----------------------------------------------------------------------------------- rendering
def _visible_rows(rep: Report, audience: str) -> list[Row]:
    return rep.rows if audience == "team" else [r for r in rep.rows if r.rag != "GREEN"]


def _approval_line(rep: Report) -> str:
    if rep.approved_by:
        return f"Approved by {rep.approved_by} on {rep.approved_at}."
    return "DRAFT - not approved. Do not forward."


def _footer(rep: Report) -> str:
    return (f"{_approval_line(rep)} Counts and dates are computed by code. The colour and reason come from "
            f"{rep.generated_by or 'the status agent'}, and a person reviewed and approved the report before it was sent. "
            "A row marked (fallback) means the AI answer was rejected by the checker and simple rules were used.")


def render_text(rep: Report, audience: str, intro: str = "") -> str:
    out = [f"{rep.program} - weekly status {rep.as_of}", f"Overall: {rep.headline()}", ""]
    if intro:
        out += [intro, ""]
    if rep.decisions:
        out += ["DECISIONS NEEDED"] + [f"  - {d}" for d in rep.decisions] + [""]
    rows = _visible_rows(rep, audience)
    greens = len(rep.rows) - len([r for r in rep.rows if r.rag != "GREEN"])
    out.append("WORKSTREAMS" if audience == "team" else "WORKSTREAMS NEEDING ATTENTION")
    for r in rows:
        tag = r.rag + (" (fallback)" if r.fallback else "")
        out.append(f"  [{tag}] {r.workstream}: done {r.done}, overdue {r.overdue}, blocked {r.blocked}, stale {r.stale}")
        out.append(f"      {r.why}")
    if not rows:
        out.append("  None. Every workstream is on track.")
    if audience == "exec" and greens:
        out.append(f"  ({greens} other workstream(s) on track, shown in the team view.)")
    out += ["", "--", _footer(rep)]
    return "\n".join(out) + "\n"


def render_html(rep: Report, audience: str, intro: str = "") -> str:
    e = html.escape
    chip = lambda rag, fb: (f'<span style="background:{COLOURS[rag]};color:#fff;padding:2px 8px;border-radius:10px;'
                            f'font-weight:600;font-size:12px">{rag}{" (fallback)" if fb else ""}</span>')
    parts = [
        '<div style="font-family:Segoe UI,Arial,sans-serif;font-size:14px;color:#222;max-width:720px">',
        f'<h2 style="margin:0 0 4px">{e(rep.program)} - weekly status {e(rep.as_of)}</h2>',
        f'<p style="margin:0 0 12px;color:#555">Overall: <b>{e(rep.headline())}</b></p>',
    ]
    if intro:
        parts.append(f"<p>{e(intro)}</p>")
    if rep.decisions:
        parts.append('<div style="border-left:4px solid #b03a2e;background:#fbeeee;padding:8px 12px;margin:12px 0">'
                     "<b>Decisions needed</b><ul style=\"margin:6px 0 0 18px;padding:0\">"
                     + "".join(f"<li>{e(d)}</li>" for d in rep.decisions) + "</ul></div>")
    rows = _visible_rows(rep, audience)
    greens = len(rep.rows) - len([r for r in rep.rows if r.rag != "GREEN"])
    parts.append('<table style="border-collapse:collapse;width:100%">'
                 '<tr style="background:#f2f2f2;text-align:left">'
                 + "".join(f'<th style="padding:6px 8px;border-bottom:1px solid #ccc">{h}</th>'
                           for h in ("Workstream", "Status", "Done", "Overdue", "Blocked", "Stale", "Why")) + "</tr>")
    for r in rows:
        td = 'style="padding:6px 8px;border-bottom:1px solid #eee;vertical-align:top"'
        parts.append(f"<tr><td {td}><b>{e(r.workstream)}</b></td><td {td}>{chip(r.rag, r.fallback)}</td>"
                     f"<td {td}>{e(r.done)}</td><td {td}>{e(r.overdue)}</td><td {td}>{e(r.blocked)}</td>"
                     f"<td {td}>{e(r.stale)}</td><td {td}>{e(r.why)}</td></tr>")
    if not rows:
        parts.append('<tr><td colspan="7" style="padding:8px">None. Every workstream is on track.</td></tr>')
    parts.append("</table>")
    if audience == "exec" and greens:
        parts.append(f'<p style="color:#555">{greens} other workstream(s) are on track (see the team view).</p>')
    parts.append(f'<p style="color:#777;font-size:12px;margin-top:16px">{e(_footer(rep))}</p></div>')
    return "".join(parts)


# ----------------------------------------------------------------------------------- messages
def _message(sender: str, to_name: str, to_email: str, subject: str, text: str, html_body: str,
             reply_to: tuple[str, str] | None = None) -> EmailMessage:
    msg = EmailMessage()
    msg["From"] = sender
    msg["To"] = formataddr((to_name, to_email))
    msg["Subject"] = subject
    msg["Date"] = formatdate(localtime=False)
    msg["Message-ID"] = make_msgid(domain="pm-ai-toolkit.local")
    if reply_to:
        msg["Reply-To"] = formataddr(reply_to)
    msg.set_content(text)
    msg.add_alternative(html_body, subtype="html")
    return msg


def review_request(rep: Report, cfg: dict, sender: str, draft_name: str, draft_text: str) -> list[tuple[str, EmailMessage]]:
    ap = cfg["approver"]
    intro = (f"A DRAFT status report is ready for your review: {rep.headline()}. "
             f"Nothing has been sent to anyone else. Read it, then approve it with: "
             f"python -m modules.m01_status_agent.run --approve out/{draft_name} --approver \"{ap['name']}\" "
             f"and send it with: python -m modules.m01_status_agent.notify publish --final out/"
             f"{draft_name.replace('DRAFT', 'FINAL')}")
    rep_view = Report(rep.program, rep.as_of, None, None, rep.generated_by, rep.rows, rep.decisions)
    subject = f"[Review needed] {rep.program} status {rep.as_of} (draft: {rep.headline()})"
    msg = _message(sender, ap["name"], ap["email"], subject,
                   render_text(rep_view, "team", intro), render_html(rep_view, "team", intro))
    msg.add_attachment(draft_text.encode("utf-8"), maintype="text", subtype="markdown", filename=draft_name)
    return [("review_request", msg)]


def publish_messages(rep: Report, cfg: dict, sender: str) -> tuple[list[tuple[str, EmailMessage]], list[str]]:
    ap = cfg["approver"]
    reply = (ap["name"], ap["email"])
    out: list[tuple[str, EmailMessage]] = []
    for s in cfg["stakeholders"]:
        subject = f"[Status] {rep.program} {rep.as_of}: {rep.headline()}"
        out.append(("stakeholder_" + s["audience"], _message(sender, s["name"], s["email"], subject,
                   render_text(rep, s["audience"]), render_html(rep, s["audience"]), reply)))
    skipped: list[str] = []
    for r in rep.rows:
        if r.rag == "GREEN":
            continue
        owner = cfg["workstream_owners"].get(r.workstream)
        if not owner:
            skipped.append(f"{r.workstream} ({r.rag}): no owner in config, no check-in sent")
            continue
        intro = (f"{r.workstream} is {r.rag} in the approved status of {rep.as_of}. Reason: {r.why.rstrip('.')}. "
                 "Please reply to this email with: (1) the cause in one line, (2) your recovery plan and the date "
                 "it is back on track, (3) any help or decision you need and from whom.")
        one = Report(rep.program, rep.as_of, rep.approved_by, rep.approved_at, rep.generated_by, [r],
                     [d for d in rep.decisions if r.workstream in d], overall=rep.headline())
        subject = f"[Check-in] {r.workstream} is {r.rag} - {rep.program} status {rep.as_of}"
        out.append(("owner_checkin", _message(sender, owner["name"], owner["email"], subject,
                    render_text(one, "team", intro), render_html(one, "team", intro), reply)))
    return out, skipped


# ----------------------------------------------------------------------------------- reminders
def _hours(h: float) -> str:
    return f"{h:.0f}" if abs(h - round(h)) < 0.05 else f"{h:.1f}"


def due_reminders(entries: list[dict], draft_name: str, now: datetime, after: float, escalate_after: float,
                  has_escalation: bool) -> tuple[list[int], float, str]:
    """Decide which reminder levels are due. Returns (levels, hours_waiting, note).

    Level 1 goes to the approver, level 2 (escalation) to the escalation contact. Nothing is due once the draft is
    approved, and a level that was already really sent (email or Slack) is never sent twice.
    """
    created = [e for e in entries if e.get("action") == "draft_created" and e.get("draft") == draft_name]
    if not created:
        raise ValueError(f"no draft_created record for {draft_name} in the audit log")
    if any(e.get("action") == "approved" and e.get("draft") == draft_name for e in entries):
        return [], 0.0, "already approved; no reminder needed"
    hours = (now - datetime.fromisoformat(created[-1]["ts"])).total_seconds() / 3600
    sent = {e.get("kind") for e in entries
            if e.get("action") in ("email_sent", "slack_sent") and e.get("report") == draft_name}
    levels = []
    if hours >= after and not ({"reminder_1", "slack_reminder"} & sent):
        levels.append(1)
    if hours >= escalate_after:
        if not has_escalation:
            return levels, hours, "escalation is due but no escalation contact is configured"
        if not ({"reminder_2", "slack_escalation"} & sent):
            levels.append(2)
    return levels, hours, ""


def reminder_messages(rep: Report, cfg: dict, sender: str, draft_name: str, level: int, hours: float) -> list[tuple[str, EmailMessage]]:
    ap = cfg["approver"]
    final_name = draft_name.replace("DRAFT", "FINAL")
    if level == 1:
        intro = (f"The draft status report has been waiting {_hours(hours)} hours for your approval, and the stakeholders have not "
                 f"been updated yet. Read it, approve it, then publish: python -m modules.m01_status_agent.run --approve out/{draft_name} "
                 f"--approver \"{ap['name']}\" and python -m modules.m01_status_agent.notify publish --final out/{final_name} --via both --send")
        view = Report(rep.program, rep.as_of, None, None, rep.generated_by, rep.rows, rep.decisions)
        subject = f"[Reminder] Draft awaiting your approval: {rep.program} {rep.as_of} ({rep.headline()})"
        msg = _message(sender, ap["name"], ap["email"], subject, render_text(view, "team", intro), render_html(view, "team", intro))
        return [("reminder_1", msg)]
    esc = cfg["escalation"]
    text = (f"{rep.program} status {rep.as_of}: the draft status report has been waiting {_hours(hours)} hours for approval "
            f"by {ap['name']}, so stakeholders have not received this week's update.\n\nOverall in the draft: {rep.headline()}.\n\n"
            f"Please contact {ap['name']} ({ap['email']}) or arrange another approver. You are receiving this because you are "
            "the configured escalation contact. The report itself has not been shared with you.\n")
    body = (f"<div style=\"font-family:Segoe UI,Arial,sans-serif;font-size:14px;max-width:640px\"><p><b>{html.escape(rep.program)} status "
            f"{html.escape(rep.as_of)}</b>: the draft status report has been waiting {_hours(hours)} hours for approval by "
            f"{html.escape(ap['name'])}, so stakeholders have not received this week's update.</p><p>Overall in the draft: "
            f"<b>{html.escape(rep.headline())}</b>.</p><p>Please contact {html.escape(ap['name'])} "
            f"(<a href=\"mailto:{html.escape(ap['email'])}\">{html.escape(ap['email'])}</a>) or arrange another approver. You are receiving "
            "this because you are the configured escalation contact. The report itself has not been shared with you.</p></div>")
    subject = f"[Escalation] {rep.program} status {rep.as_of} is unapproved after {_hours(hours)}h"
    return [("reminder_2", _message(sender, esc["name"], esc["email"], subject, text, body, (ap["name"], ap["email"])))]


def _remind(a, cfg: dict, log: AuditLog, out: Path) -> int:
    path = Path(a.draft)
    text = path.read_text(encoding="utf-8")
    rep = parse_report(text)
    if rep.approved_by:
        print("note: this report is already approved; no reminder needed")
        return 0
    rcfg = cfg.get("reminders") or {}
    after = a.after_hours if a.after_hours is not None else rcfg.get("after_hours", 2)
    esc_after = a.escalate_after_hours if a.escalate_after_hours is not None else rcfg.get("escalate_after_hours", 4)
    now = datetime.fromisoformat(a.now) if a.now else datetime.now(timezone.utc)
    try:
        levels, hours, note = due_reminders(read_log(out / "audit.jsonl"), path.name, now, after, esc_after, "escalation" in cfg)
    except ValueError as exc:
        print(f"REFUSED: {exc}", file=sys.stderr)
        return 2
    if note:
        print("note:", note)
    if not levels:
        print(f"no reminder due ({_hours(hours)}h since the draft was created)")
        return 0
    use_email, use_slack = a.via in ("email", "both"), a.via in ("slack", "both")
    sender = os.environ.get("SMTP_FROM") or "pm-ai-toolkit@example.invalid"
    sha = fingerprint(text)
    mode = "sent" if a.send else f"prepared (dry run, nothing sent) in {out / 'outbox'}"
    failed_total = 0
    for level in levels:
        if use_email:
            ok, failed = deliver(reminder_messages(rep, cfg, sender, path.name, level, hours), path.name, sha, log, out / "outbox", a.send)
            print(f"reminder level {level}: {ok} email(s) {mode}; {failed} failed")
            failed_total += failed
        if use_slack:
            from modules.m01_status_agent import slack_notify
            ok, failed, notes = slack_notify.deliver(slack_notify.reminder_items(rep, cfg, path.name, level, hours), path.name, sha,
                                                    log, out / "outbox", a.send, os.environ)
            print(f"reminder level {level}: {ok} Slack message(s) {mode}; {failed} failed")
            for n in notes:
                print("note:", n)
            failed_total += failed
    return 1 if failed_total else 0


# ----------------------------------------------------------------------------------- delivery
def _smtp_settings() -> dict:
    missing = [k for k in ("SMTP_HOST", "SMTP_FROM") if not os.environ.get(k)]
    if missing:
        raise RuntimeError("to send for real, set environment variable(s): " + ", ".join(missing)
                           + " (optional: SMTP_PORT, SMTP_USER, SMTP_PASSWORD, SMTP_SECURITY=starttls|ssl)")
    security = os.environ.get("SMTP_SECURITY", "starttls").lower()
    if security not in ("starttls", "ssl"):
        raise RuntimeError("SMTP_SECURITY must be 'starttls' or 'ssl'; unencrypted sending is not supported")
    default_port = 465 if security == "ssl" else 587
    return {"host": os.environ["SMTP_HOST"], "port": int(os.environ.get("SMTP_PORT", default_port)),
            "user": os.environ.get("SMTP_USER"), "password": os.environ.get("SMTP_PASSWORD"),
            "from": os.environ["SMTP_FROM"], "security": security}


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def deliver(items: list[tuple[str, EmailMessage]], report_name: str, report_sha: str, log: AuditLog,
            outbox: Path, send: bool) -> tuple[int, int]:
    """Write .eml files (dry run) or send. Returns (ok, failed)."""
    ok = failed = 0
    if not send:
        outbox.mkdir(parents=True, exist_ok=True)
        for kind, msg in items:
            to = msg["To"].split("<")[-1].rstrip(">")
            path = outbox / f"{kind}_{_slug(to)}.eml"
            path.write_bytes(bytes(msg))
            log.record("system", "email_prepared", kind=kind, to=to, subject=msg["Subject"],
                       report=report_name, report_sha=report_sha, file=path.name)
            ok += 1
        return ok, failed
    cfg = _smtp_settings()
    cls = smtplib.SMTP_SSL if cfg["security"] == "ssl" else smtplib.SMTP
    for kind, msg in items:
        to = msg["To"].split("<")[-1].rstrip(">")
        try:
            with cls(cfg["host"], cfg["port"], timeout=30) as smtp:
                smtp.ehlo()
                if cfg["security"] == "starttls":
                    smtp.starttls(context=ssl.create_default_context())
                    smtp.ehlo()
                if cfg["user"]:
                    smtp.login(cfg["user"], cfg["password"] or "")
                smtp.send_message(msg)
            log.record("system", "email_sent", kind=kind, to=to, subject=msg["Subject"],
                       report=report_name, report_sha=report_sha)
            ok += 1
        except Exception as exc:  # never log the exception text: it can echo credentials or addresses
            log.record("system", "email_failed", kind=kind, to=to, error=type(exc).__name__, report=report_name)
            failed += 1
    return ok, failed


# ----------------------------------------------------------------------------------- CLI
def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    for name in ("review-request", "publish"):
        sp = sub.add_parser(name)
        sp.add_argument("--draft" if name == "review-request" else "--final", required=True)
        sp.add_argument("--config", default="config/stakeholders.json")
        sp.add_argument("--out", default="out")
        sp.add_argument("--via", choices=["email", "slack", "both"], default="email",
                        help="where to send; default email")
        sp.add_argument("--send", action="store_true",
                        help="really send; default is to write .eml / .json files only")
    rp = sub.add_parser("remind", help="remind the approver (and optionally an escalation contact) about an unapproved draft")
    rp.add_argument("--draft", required=True)
    rp.add_argument("--config", default="config/stakeholders.json")
    rp.add_argument("--out", default="out")
    rp.add_argument("--via", choices=["email", "slack", "both"], default="email")
    rp.add_argument("--send", action="store_true")
    rp.add_argument("--after-hours", type=float, default=None, help="first reminder after this many hours (default 2)")
    rp.add_argument("--escalate-after-hours", type=float, default=None, help="escalate after this many hours (default 4)")
    rp.add_argument("--now", default=None, help=argparse.SUPPRESS)
    a = p.parse_args(argv)
    out = Path(a.out)
    log = AuditLog(out / "audit.jsonl")
    try:
        cfg = load_config(a.config)
    except (FileNotFoundError, ValueError) as exc:
        print(f"CONFIG PROBLEM: {exc}", file=sys.stderr)
        return 2
    if a.cmd == "remind":
        return _remind(a, cfg, log, out)
    sender = os.environ.get("SMTP_FROM") or "pm-ai-toolkit@example.invalid"
    use_email, use_slack = a.via in ("email", "both"), a.via in ("slack", "both")
    skipped: list[str] = []
    items: list = []
    slack_items: list = []

    if a.cmd == "review-request":
        path = Path(a.draft)
        text = path.read_text(encoding="utf-8")
        rep = parse_report(text)
        if rep.approved_by:
            p.error("this report is already approved; use 'publish' instead")
        if use_email:
            items = review_request(rep, cfg, sender, path.name, text)
        if use_slack:
            from modules.m01_status_agent import slack_notify
            slack_items = slack_notify.review_items(rep, cfg, path.name)
    else:
        path = Path(a.final)
        try:
            if not path.exists():
                raise ValueError(f"{path} does not exist; approve the draft first")
            verify_approved(path, out / "audit.jsonl")
        except ValueError as exc:
            print(f"REFUSED: {exc}", file=sys.stderr)
            return 2
        text = path.read_text(encoding="utf-8")
        rep = parse_report(text)
        if use_email:
            items, skipped = publish_messages(rep, cfg, sender)
        if use_slack:
            from modules.m01_status_agent import slack_notify
            slack_items = slack_notify.publish_items(rep, cfg)

    sha = fingerprint(text)
    mode = "sent" if a.send else f"prepared (dry run, nothing sent) in {out / 'outbox'}"
    failed_total = 0
    if items:
        ok, failed = deliver(items, path.name, sha, log, out / "outbox", a.send)
        print(f"{ok} email(s) {mode}; {failed} failed")
        failed_total += failed
    if slack_items:
        from modules.m01_status_agent import slack_notify
        ok, failed, notes = slack_notify.deliver(slack_items, path.name, sha, log, out / "outbox", a.send, os.environ)
        print(f"{ok} Slack message(s) {mode}; {failed} failed")
        skipped += notes
        failed_total += failed
    for s in skipped:
        print("note:", s)
    return 1 if failed_total else 0


