"""Email notifications for the status agent. Approval-gated, dry-run by default.

Three commands (add --via slack or --via both to also post to Slack; see slack_notify.py):

  review-request  Tell the approver a DRAFT is waiting (sent to the approver only, draft attached).
  remind          If a draft is still unapproved after N hours, remind the approver; after M hours, escalate
                  (headline only) to the configured escalation contact. Safe to run repeatedly.
  publish         After a report is APPROVED: email the stakeholders (exec or team view) and send a
                  check-in to the owner of every RED or AMBER workstream.

Rules built into the code:
  * publish refuses a report that is a draft, has no approval record in the audit log, or was edited
    after approval (fingerprint check). Stakeholders only ever receive exactly what was approved.
  * Nothing is sent unless you pass --send. Without it, ready-to-read .eml files are written to
    out/outbox/ so a person can inspect them.
  * SMTP credentials come only from environment variables. Recipient addresses live in
    config/stakeholders.json, which is git-ignored.

  python -m modules.m01_status_agent.notify review-request --draft out/status_2026-03-20_DRAFT.md
  python -m modules.m01_status_agent.notify publish --final out/status_2026-03-20_FINAL.md
  add --send to really send (needs SMTP_HOST and SMTP_FROM; see SETUP.md).

STATUS: tested with a simulated SMTP server in unit tests; NOT yet tested against a real mail server.
"""
